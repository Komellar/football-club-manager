import {
  WebSocketGateway,
  SubscribeMessage,
  MessageBody,
  WebSocketServer,
  ConnectedSocket,
  OnGatewayConnection,
  OnGatewayDisconnect,
  WsException,
} from '@nestjs/websockets';
import { Logger, UseFilters, OnModuleDestroy } from '@nestjs/common';
import { OnEvent } from '@nestjs/event-emitter';
import { Server, Socket } from 'socket.io';
import { MatchEventsService } from '../services/match-events.service';
import {
  AuthService,
  SESSIONS_REVOKED_EVENT,
} from '../../auth/services/auth.service';
import { AUTH_COOKIE_NAME } from '../../../shared/guards/session-token';
import {
  allowedOrigins,
  allowWebSocketRequest,
} from '../../../config/origins.config';
import {
  SubscribeToMatch,
  UnsubscribeFromMatch,
  SubscribeToMatchSchema,
  UnsubscribeFromMatchSchema,
  StartFixtureSchema,
  MatchEventsSocketMessage,
  MatchEvent,
  MatchEnded,
  MatchSimulationState,
} from '@repo/core';
import { WsValidationPipe } from '../../../shared/pipes/ws-validation.pipe';
import { WsExceptionFilter } from '../../../shared/filters/ws-exception.filter';
import {
  ACTIVE_MATCH_ROOM,
  MATCH_INTERNAL_EVENT,
  MATCH_INTERNAL_ENDED,
  MATCH_INTERNAL_STATE,
} from '../constants/match-simulation.constants';

/**
 * WebSocket Gateway for real-time match events.
 * Only one match can run at a time. All subscribers join the same room
 * (ACTIVE_MATCH_ROOM) and receive every broadcast. The matchId is a UUID
 * generated by the backend — clients never supply it.
 */
@WebSocketGateway({
  cors: {
    // Evaluated per request: FRONTEND_URL may come from .env after import.
    origin: (
      origin: string | undefined,
      callback: (err: Error | null, allow?: boolean) => void,
    ) => callback(null, !origin || allowedOrigins().includes(origin)),
    credentials: true,
  },
  allowRequest: allowWebSocketRequest,
  namespace: 'match-events',
  transports: ['websocket'],
})
@UseFilters(new WsExceptionFilter())
export class MatchEventsGateway
  implements OnGatewayConnection, OnGatewayDisconnect, OnModuleDestroy
{
  @WebSocketServer()
  server!: Server;

  private readonly logger = new Logger(MatchEventsGateway.name);
  private readonly expiryTimers = new Map<
    string,
    ReturnType<typeof setTimeout>
  >();
  /** Which user each authenticated socket belongs to, for revocation. */
  private readonly socketUsers = new Map<string, number>();
  private readonly sockets = new Map<string, Socket>();

  constructor(
    private readonly matchEventsService: MatchEventsService,
    private readonly auth: AuthService,
  ) {}

  handleConnection(client: Socket) {
    this.logger.log(`Client connected: ${client.id}`);
  }

  handleDisconnect(client: Socket) {
    clearTimeout(this.expiryTimers.get(client.id));
    this.expiryTimers.delete(client.id);
    this.socketUsers.delete(client.id);
    this.sockets.delete(client.id);
    this.logger.log(`Client disconnected: ${client.id}`);
    try {
      this.matchEventsService.handleClientDisconnect(client.id);
    } catch (error) {
      this.logger.error(`Error handling disconnect for ${client.id}:`, error);
    }
  }

  onModuleDestroy() {
    for (const timer of this.expiryTimers.values()) clearTimeout(timer);
    this.expiryTimers.clear();
  }

  @SubscribeMessage(MatchEventsSocketMessage.SUBSCRIBE_TO_MATCH)
  async handleSubscribeToMatch(
    @MessageBody(new WsValidationPipe(SubscribeToMatchSchema))
    _data: SubscribeToMatch,
    @ConnectedSocket() client: Socket,
  ) {
    await this.authenticate(client);
    const matchId = this.matchEventsService.subscribeToMatch(client.id);
    await client.join(ACTIVE_MATCH_ROOM);
    return {
      success: true,
      matchId,
      state: this.matchEventsService.getActiveMatch(),
    };
  }

  @SubscribeMessage(MatchEventsSocketMessage.UNSUBSCRIBE_FROM_MATCH)
  async handleUnsubscribeFromMatch(
    @MessageBody(new WsValidationPipe(UnsubscribeFromMatchSchema))
    _data: UnsubscribeFromMatch,
    @ConnectedSocket() client: Socket,
  ) {
    this.matchEventsService.unsubscribeFromMatch(client.id);
    await client.leave(ACTIVE_MATCH_ROOM);
    return { success: true };
  }

  @SubscribeMessage(MatchEventsSocketMessage.START_MATCH)
  async handleStartMatch(
    @MessageBody(new WsValidationPipe(StartFixtureSchema))
    data: { fixtureId: string },
    @ConnectedSocket() client: Socket,
  ) {
    try {
      await this.authenticate(client);
      await client.join(ACTIVE_MATCH_ROOM);
      const state = await this.matchEventsService.startFixture(data.fixtureId);
      this.server.to(ACTIVE_MATCH_ROOM).emit('matchState', state);
      return { success: true, matchId: state.matchId, state };
    } catch (error) {
      return {
        success: false,
        message:
          error instanceof Error ? error.message : 'Could not start match',
      };
    }
  }

  private async authenticate(client: Socket) {
    const cookie = client.handshake.headers.cookie
      ?.split(';')
      .map((part) => part.trim())
      .find((part) => part.startsWith(`${AUTH_COOKIE_NAME}=`))
      ?.slice(AUTH_COOKIE_NAME.length + 1);
    const handshakeToken: unknown = client.handshake.auth?.token;
    const token = typeof handshakeToken === 'string' ? handshakeToken : cookie;
    try {
      if (!token) throw new Error('Missing token');
      const { user, expiresAt } = await this.auth.verifySession(
        decodeURIComponent(token),
      );
      this.socketUsers.set(client.id, user.userId);
      this.sockets.set(client.id, client);
      clearTimeout(this.expiryTimers.get(client.id));
      this.expiryTimers.set(
        client.id,
        setTimeout(
          () => client.disconnect(true),
          Math.max(0, expiresAt.getTime() - Date.now()),
        ),
      );
    } catch {
      throw new WsException('Please sign in to access matches');
    }
  }

  /** Logging out revokes the user's sessions; drop their open sockets too. */
  @OnEvent(SESSIONS_REVOKED_EVENT)
  onSessionsRevoked(userId: number) {
    for (const [socketId, owner] of this.socketUsers) {
      if (owner === userId) this.sockets.get(socketId)?.disconnect(true);
    }
  }

  @OnEvent(MATCH_INTERNAL_EVENT)
  onMatchEvent(event: MatchEvent) {
    this.server.to(ACTIVE_MATCH_ROOM).emit('matchEvent', event);
  }

  @OnEvent(MATCH_INTERNAL_ENDED)
  onMatchEnded(payload: MatchEnded) {
    this.server.to(ACTIVE_MATCH_ROOM).emit('matchEnded', payload);
  }

  @OnEvent(MATCH_INTERNAL_STATE)
  onMatchState(state: MatchSimulationState) {
    this.server.to(ACTIVE_MATCH_ROOM).emit('matchState', state);
  }
}
